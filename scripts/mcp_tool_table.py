"""Print the registered MCP tools as a markdown table, grouped by module (family).

Used to keep docs/mcp.md honest:  python scripts/mcp_tool_table.py
Each row: tool name, access (view / change / change with confirm code), first sentence of its description.
"""
import asyncio
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from ai.mcp import mcp  # noqa: E402


def first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text).replace("|", "/")


async def main():
    tools = await mcp.get_tools()
    families: dict[str, list] = {}
    for name, tool in tools.items():
        fam = getattr(tool.fn, "__module__", "?").rsplit(".", 1)[-1].removesuffix("_mcp")
        families.setdefault(fam, []).append((name, tool))
    print(f"<!-- {len(tools)} tools; generated by scripts/mcp_tool_table.py -->")
    for fam in sorted(families):
        print(f"\n### {fam}\n\n| Tool | Access | What it does |\n|---|---|---|")
        for name, tool in sorted(families[fam]):
            tags = set(tool.tags or [])
            access = "make changes + confirm code" if "live" in tags else ("make changes" if "write" in tags else "view")
            print(f"| `{name}` | {access} | {first_sentence(tool.description)} |")


asyncio.run(main())
