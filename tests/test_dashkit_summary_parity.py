"""
tests/test_dashkit_summary_parity.py
------------------------------------
Parity guard for the Python port of dashkit's `summarize` (`summarize_doc`).

tests/fixtures/dashkit_summary_parity.json is generated by dashkit's
scripts/gen-birdy-parity.ts (run by scripts/sync_dashkit_schema.sh in the
dashkit repo): a fixed, seeded set of v1 docs with dashkit's
`summarize(migrate(doc))`, their migrated v3 docs with `summarize(doc)`, and
seeded v3 docs whose queries carry every part the `query:` line prints.
`summarize_doc` must reproduce every string, migrating v1 docs itself
(flattened to v2, then bindings turned into one query per widget).

When this fails after a dashkit change, port the change to summarize_doc /
the migration, re-run the sync script and commit the regenerated fixture.
"""

import json
from pathlib import Path

import pytest

from ai.tools.dashboard_tools import summarize_doc

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "dashkit_summary_parity.json"


def _rows(kind):
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    return [pytest.param(row["doc"], row["summary"], id=f'{kind}-{row["doc"]["id"]}') for row in data[kind]]


def test_fixture_covers_v1_and_v3():
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert len(data["v1"]) >= 20 and len(data["v3"]) >= 40
    assert all(row["doc"]["version"] == 1 for row in data["v1"])
    assert all(row["doc"]["version"] == 3 for row in data["v3"])
    lines = "\n".join(row["summary"] for row in data["v1"] + data["v3"])
    # Every optional part of the query line is exercised somewhere.
    for part in (" by=", " over=", " compare", " spark", " nospark", " sort=", " limit=", " filters=", ':"', ".."):
        assert part in lines, part


@pytest.mark.parametrize(("doc", "summary"), _rows("v1"))
def test_summarize_doc_v1_matches_dashkit(doc, summary):
    assert summarize_doc(doc) == summary


@pytest.mark.parametrize(("doc", "summary"), _rows("v3"))
def test_summarize_doc_v3_matches_dashkit(doc, summary):
    assert summarize_doc(doc) == summary
