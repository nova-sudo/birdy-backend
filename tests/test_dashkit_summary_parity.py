"""
tests/test_dashkit_summary_parity.py
------------------------------------
Parity guard for the Python port of dashkit's `summarize` (`summarize_doc`).

tests/fixtures/dashkit_summary_parity.json is generated by dashkit's
scripts/gen-birdy-parity.ts (run by scripts/sync_dashkit_schema.sh in the
dashkit repo): a fixed, seeded set of v1 docs with dashkit's
`summarize(migrate(doc))`, and their migrated v2 docs with `summarize(doc)`.
`summarize_doc` must reproduce every string, flattening v1 docs itself.

When this fails after a dashkit change, port the change to summarize_doc /
the v1 flattening, re-run the sync script and commit the regenerated fixture.
"""

import json
from pathlib import Path

import pytest

from ai.tools.dashboard_tools import summarize_doc

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "dashkit_summary_parity.json"


def _rows(kind):
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    return [pytest.param(row["doc"], row["summary"], id=f'{kind}-{row["doc"]["id"]}') for row in data[kind]]


def test_fixture_covers_v1_and_v2():
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert len(data["v1"]) >= 20 and len(data["v2"]) >= 20
    assert all(row["doc"]["version"] == 1 for row in data["v1"])
    assert all(row["doc"]["version"] == 2 for row in data["v2"])


@pytest.mark.parametrize(("doc", "summary"), _rows("v1"))
def test_summarize_doc_v1_matches_dashkit(doc, summary):
    assert summarize_doc(doc) == summary


@pytest.mark.parametrize(("doc", "summary"), _rows("v2"))
def test_summarize_doc_v2_matches_dashkit(doc, summary):
    assert summarize_doc(doc) == summary
