"""
Tools for the "My dashboards" chat (page "dashboards").

The dashboard lives in the user's dashkit editor, not here: these executors
never write the stored doc. `dashboard_apply` and `dashboard_propose_widget`
check their arguments and return dashkit edit ops; ai/orchestrator.py hands
every successful batch back to the editor as `dashboard_ops`, which applies
them to the live doc and saves.

Tool names, descriptions and parameter schemas come from `dashkit_tools.json`,
generated by dashkit's `scripts/export-tools.ts` from Birdy's catalog (synced by
dashkit's `scripts/sync_dashkit_schema.sh`; never edit it by hand). The schemas
embed the catalog's metric keys, dimensions and window presets as enums, so
validating against them is what rejects an unknown metric. Ops must also name
ids that exist: the known widgets come from the editor's summary (else the
stored doc) plus the ops already returned this turn (`_Layout`).

Dashboards are dashkit v2 docs: a flat `widgets` list, each with a grid
`layout {x, y, w, h}` (12 columns of 48px rows); sections are `heading`
widgets. Stored docs saved before dashkit 0.3.0 are v1 (sections with spans)
until the editor next saves them, so `summarize_doc` and the stored-doc
fallback flatten a v1 doc the way dashkit's `migrate()` does.

The orchestrator injects three keyword arguments into these tools only:
`dashboard_id` and `summary` (the editor's `summarize(doc)` of the live doc,
unsaved edits included) from the chat request, and `dashboard_ops_sink`, the
turn's op list. Executors append their ops to the sink themselves, so ops are
collected from the raw result and can never be lost to the result-size
truncation in ai/tools/result_shaping.py.
"""

import json
import logging
import re
from pathlib import Path
from typing import Optional
from uuid import uuid4

from jsonschema import Draft202012Validator
from jsonschema.exceptions import best_match

from ai.config import MAX_RESULT_CHARS
from ai.tools.registry import registry
from services.dashboards_catalog import build_catalog

logger = logging.getLogger(__name__)

_TOOLS_PATH = Path(__file__).with_name("dashkit_tools.json")
_TOOL_DEFS: dict[str, dict] = {t["name"]: t for t in json.loads(_TOOLS_PATH.read_text(encoding="utf-8"))}

DASHBOARD_TOOL_NAMES = ("dashboard_describe", "dashboard_apply", "dashboard_propose_widget", "catalog_search")
# Tools whose successful results carry ops for the editor.
OP_TOOL_NAMES = ("dashboard_apply", "dashboard_propose_widget")

_VALIDATORS = {name: Draft202012Validator(_TOOL_DEFS[name]["parameters"]) for name in DASHBOARD_TOOL_NAMES}

# Ops the model may not emit (dashkit's FORBIDDEN_OPS); the schema already omits them.
_FORBIDDEN_OPS = ("replaceDashboard",)
_OP_MEMBERS = {
    m["properties"]["op"]["const"]: Draft202012Validator(m)
    for m in _TOOL_DEFS["dashboard_apply"]["parameters"]["properties"]["ops"]["items"]["anyOf"]
}

# dashkit 0.3.0 removed these: sections are `heading` widgets now.
_SECTION_OPS = ("addSection", "removeSection", "moveSection", "updateSection")
_SECTION_OPS_MESSAGE = ('Op "{name}" no longer exists: sections are `heading` widgets. Add one with addWidget '
                        '(type "heading"), place widgets under it with `after`, size it with updateWidgetData '
                        '`level`, and move, retitle or remove it like any widget.')

_APPLIED_NOTE = "Applied in the user's editor."
_SEARCH_LIMIT = 20
_MESSAGE_LIMIT = 300
_ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_TITLE_LINE = re.compile(r"^# (.*) \(\d+ widgets\)$")
# Markdown markers a title may not carry: titles render as plain text.
_TITLE_MARKDOWN = re.compile(r"[#*_`]")
_TITLE_MESSAGE = ("Titles are plain text; remove the markdown (#, *, _ or backticks). To make a heading "
                  "larger or smaller use updateWidgetData with `level` (1 large, 2 default, 3 small); "
                  "for prose add a `text` widget.")
# One widget line of dashkit's summarize (src/core/summarize.ts):
#   - [id] type "title" w×h @x,y[ (h1|h3)][ hidden][ locked][  slot→metric[ by dim] window; ...]
_WIDGET_LINE = re.compile(r"^- \[([^\]]+)\] ")
_WIDGET_DETAIL = re.compile(r'^- \[([^\]]+)\] (\S+) "(.*)" (\d+)×(\d+) @(\d+),(\d+)'
                            r"(?: \(h\d\))?(?: hidden)?(?: locked)?(?:  .*)?$")
# How many daily-capable metrics a by-day refusal names (keeps it under _MESSAGE_LIMIT).
_DAILY_LIST_LIMIT = 6


def widget_manifest() -> list[dict]:
    """dashkit's widget types (`x-dashkit-widgets`): type, label, aiHint, slots, default/min/max size."""
    return _TOOL_DEFS["dashboard_propose_widget"].get("x-dashkit-widgets", [])


def _manifest_entry(widget_type: str) -> Optional[dict]:
    return next((w for w in widget_manifest() if w["type"] == widget_type), None)


def _widget_types() -> list[str]:
    return [w["type"] for w in widget_manifest()]


# ── results ──────────────────────────────────────────────────────────────────


def _fail(code: str, path: str, message: str) -> dict:
    if len(message) > _MESSAGE_LIMIT:
        message = message[:_MESSAGE_LIMIT] + "…"
    return {"ok": False, "error": {"code": code, "path": path, "message": message}}


def _succeed(ops: list, sink: Optional[list], **extra) -> dict:
    if sink is not None:
        sink.extend(ops)
    result = {"ok": True, "ops": ops, "note": _APPLIED_NOTE, **extra}
    # The model only needs to know the edit landed; a huge echo of its own ops
    # would be replaced by a truncation notice telling it to retry.
    if len(json.dumps(result, default=str)) > MAX_RESULT_CHARS - 500:
        result = {"ok": True, "applied": [op.get("op") for op in ops], "note": _APPLIED_NOTE, **extra}
    return result


# ── argument validation ──────────────────────────────────────────────────────


def _pointer(path) -> str:
    return "/" + "/".join(str(p) for p in path)


def _schema_error(validator: Draft202012Validator, instance, prefix: str = "") -> Optional[dict]:
    error = best_match(validator.iter_errors(instance))
    if error is None:
        return None
    path = list(error.absolute_path)
    if error.validator == "required" and isinstance(error.instance, dict):
        missing = [p for p in error.validator_value if p not in error.instance]
        path += missing[:1]
    return _fail("ARGS_INVALID", prefix + (_pointer(path) if path else ""), error.message)


def _title_error(title, path: str) -> Optional[dict]:
    if isinstance(title, str) and _TITLE_MARKDOWN.search(title):
        return _fail("TITLE_PLAIN_TEXT", path, _TITLE_MESSAGE)
    return None


def _op_titles(op: dict, at: str, layout: "_Layout"):
    """(title, path, current title or None) for every title an op sets: the dashboard's and widgets'
    (a heading's title is its heading text)."""
    name = op["op"]
    if name == "setTitle":
        yield op.get("title"), f"{at}/title", layout.title
    elif name == "updateWidget":
        yield (op.get("patch") or {}).get("title"), f"{at}/patch/title", layout.widget_titles.get(op["widgetId"])
    elif name == "addWidget":
        yield (op.get("widget") or {}).get("title"), f"{at}/widget/title", None


def _op_title_error(op: dict, at: str, layout: "_Layout") -> Optional[dict]:
    """TITLE_PLAIN_TEXT for a title the op sets, unless it equals the current one: titles people
    typed themselves ("Client #1") must not block an op that only changes something else."""
    return next((e for title, path, current in _op_titles(op, at, layout)
                 if title != current and (e := _title_error(title, path))), None)


def _ops_error(ops) -> Optional[dict]:
    """Per-op check against that op's own schema, for precise paths and messages,
    plus the unknown-widget-type rule the schema cannot express. (Markdown in
    titles is checked against the layout in dashboard_apply.)"""
    if not isinstance(ops, list):
        return None
    for i, op in enumerate(ops):
        name = op.get("op") if isinstance(op, dict) else None
        if not isinstance(name, str):
            continue
        at = f"/ops/{i}"
        if name in _FORBIDDEN_OPS:
            return _fail("OP_FORBIDDEN", at, f'Op "{name}" is not available to tools')
        if name in _SECTION_OPS:
            return _fail("OP_INVALID", f"{at}/op", _SECTION_OPS_MESSAGE.format(name=name))
        member = _OP_MEMBERS.get(name)
        if member is None:
            return _fail("OP_INVALID", f"{at}/op", f'Unknown op "{name}"; use one of {", ".join(_OP_MEMBERS)}')
        if name == "changeWidgetType" and isinstance(op.get("type"), str) and op["type"] not in _widget_types():
            return _fail("WIDGET_TYPE_UNKNOWN", f"{at}/type",
                         f'Unknown widget type "{op["type"]}"; use one of {", ".join(_widget_types())}')
        found = _schema_error(member, op, at)
        if found:
            return found
    return None


def _binding_error(binding: dict, at: str, metrics: dict, dimensions: set) -> Optional[dict]:
    """Catalog checks the schema cannot express (dashkit's validateWidget, binding part)."""
    metric = metrics.get(binding.get("metric"))
    by = binding.get("by")
    if metric is not None and by is not None and by not in metric.get("dimensions", []):
        message = f'Metric "{metric["key"]}" cannot be split by "{by}"'
        if by == "day":
            daily = [f'`{key}`' for key, m in metrics.items() if "day" in m.get("dimensions", [])]
            if not daily:
                message += "; no metric has a daily series"
            else:
                listed = ", ".join(daily[:_DAILY_LIST_LIMIT])
                more = len(daily) - _DAILY_LIST_LIMIT
                message += f"; metrics with a daily series: {listed}" + (f" and {more} more" if more > 0 else "")
        return _fail("DIMENSION_NOT_ALLOWED", f"{at}/by", message)
    for dim in (binding.get("filters") or {}):
        if dim not in dimensions:
            return _fail("FILTER_DIMENSION_UNKNOWN", f"{at}/filters/{dim}", f'Unknown filter dimension "{dim}"')
    window = binding.get("window") or {}
    if "from" in window and by != "day":
        # The resolver reads value and by-client numbers from cached presets only;
        # a custom range would render as an error on the widget.
        return _fail("WINDOW_UNSUPPORTED", f"{at}/window",
                     'Custom {from, to} windows only work with by: "day"; '
                     'use a window preset (e.g. last_30d) or split the metric by "day"')
    if "from" in window:
        for edge in ("from", "to"):
            if not _ISO_DATE.match(str(window.get(edge, ""))):
                return _fail("WINDOW_RANGE_INVALID", f"{at}/window/{edge}", f'"{edge}" must be YYYY-MM-DD')
        if window["from"] > window["to"]:
            return _fail("WINDOW_RANGE_INVALID", f"{at}/window/from", '"from" is after "to"')
    return None


def _catalog_index() -> tuple[dict, set]:
    catalog = build_catalog()
    return {m["key"]: m for m in catalog["metrics"]}, {d["key"] for d in catalog["dimensions"]}


# ── the dashboard as the model sees it ───────────────────────────────────────

_GRID_COLS = 12
# A v1 row is two v2 rows (dashkit's ROWS_PER_V1_ROW).
_ROWS_PER_V1_ROW = 2


def _binding_text(slot: str, binding: dict) -> str:
    window = binding.get("window") or {}
    when = window["preset"] if "preset" in window else f'{window.get("from")}..{window.get("to")}'
    by = f' by {binding["by"]}' if binding.get("by") else ""
    return f'{slot}→{binding.get("metric")}{by} {when}'


def _heading_level(widget: dict) -> int:
    """dashkit's headingLevel: a heading's `data.level` when it is 1 or 3, else 2 (also for non-headings)."""
    data = widget.get("data")
    if widget.get("type") != "heading" or not isinstance(data, dict):
        return 2
    level = data.get("level")
    if isinstance(level, bool) or not isinstance(level, (int, float)):
        return 2
    return int(level) if level in (1, 3) else 2


def _grid(widget: dict) -> dict:
    layout = widget.get("layout")
    layout = layout if isinstance(layout, dict) else {}
    return {k: layout.get(k, 0) for k in ("x", "y", "w", "h")}


def _widget_line(widget: dict) -> str:
    g = _grid(widget)
    title = widget.get("title")
    line = (f'- [{widget.get("id")}] {widget.get("type")} "{"" if title is None else title}" '
            f'{g["w"]}×{g["h"]} @{g["x"]},{g["y"]}')
    level = _heading_level(widget)
    if widget.get("type") == "heading" and level != 2:
        line += f" (h{level})"
    if widget.get("hidden"):
        line += " hidden"
    if widget.get("locked"):
        line += " locked"
    bindings = (widget.get("bindings") or {}).items()
    if bindings:
        line += "  " + "; ".join(_binding_text(slot, b) for slot, b in bindings)
    return line


# The v1 → v2 flattening is a port of dashkit's migrateV1toV2 (src/core/migrate.ts)
# and of the vertical compaction in its normalizeLayout (src/core/layout.ts, itself
# react-grid-layout's verticalCompactor), so a stored v1 doc gets the same ids,
# sizes and positions here as in the editor after it migrates the doc on load.


class _Cell:
    """A mutable layout under compaction; compared by identity, like dashkit's items."""

    __slots__ = ("index", "x", "y", "w", "h")

    def __init__(self, index: int, layout: dict):
        self.index = index
        self.x, self.y, self.w, self.h = layout["x"], layout["y"], layout["w"], layout["h"]


def _collides(a: _Cell, b: _Cell) -> bool:
    return a is not b and not (a.x + a.w <= b.x or a.x >= b.x + b.w or a.y + a.h <= b.y or a.y >= b.y + b.h)


def _resolve_compaction_collision(ordered: list, item: _Cell, move_to_y: int) -> None:
    item.y += 1
    start = next(i for i, c in enumerate(ordered) if c is item)
    for other in ordered[start + 1:]:
        if other.y > item.y + item.h:
            break
        if _collides(item, other):
            _resolve_compaction_collision(ordered, other, move_to_y + item.h)
    item.y = move_to_y


def _compact(widgets: list[dict]) -> list[dict]:
    """dashkit's normalizeLayout with nothing pinned: vertical compaction, then (y, x, input order)."""
    cells = [_Cell(i, w["layout"]) for i, w in enumerate(widgets)]
    ordered = sorted(cells, key=lambda c: (c.y, c.x, c.index))
    placed: list[_Cell] = []
    max_y = 0
    for item in ordered:
        item.x, item.y = max(item.x, 0), min(max_y, max(item.y, 0))
        while item.y > 0 and not any(_collides(c, item) for c in placed):
            item.y -= 1
        while (hit := next((c for c in placed if _collides(c, item)), None)) is not None:
            _resolve_compaction_collision(ordered, item, hit.y + hit.h)
        item.y = max(item.y, 0)
        max_y = max(max_y, item.y + item.h)
        placed.append(item)
    out = []
    for c in sorted(cells, key=lambda c: (c.y, c.x, c.index)):
        out.append({**widgets[c.index], "layout": {"x": c.x, "y": c.y, "w": c.w, "h": c.h}})
    return out


def _number(value, default):
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else default


def _v1_size(widget: dict) -> tuple:
    """w = span.cols, h = span.rows × 2, clamped to the type's min/max when the type is known."""
    span = widget.get("span") if isinstance(widget.get("span"), dict) else {}
    w = _number(span.get("cols"), _GRID_COLS)
    h = _number(span.get("rows"), 1) * _ROWS_PER_V1_ROW
    entry = _manifest_entry(widget.get("type"))
    if entry:
        lo, hi = entry["minSize"], entry["maxSize"]
        w, h = min(max(w, lo["w"]), hi["w"]), min(max(h, lo["h"]), hi["h"])
    return w, h


def _unique_heading_id(section_id, used: set) -> str:
    """The section id, or `<id>-heading`, `<id>-heading-2`, ... when a widget (or earlier heading) has it."""
    candidate, n = section_id, 1
    while candidate in used:
        candidate = f"{section_id}-heading" if n == 1 else f"{section_id}-heading-{n}"
        n += 1
    used.add(candidate)
    return candidate


def _flatten_v1(doc: dict) -> list[dict]:
    """A v1 doc's widgets as v2 widgets: each titled section becomes a `heading` (12×1, 12×2 with a
    description) followed by its widgets, shelf-packed left to right, each section on a new shelf,
    then compacted. Untitled sections leave no heading; `collapsed` is dropped."""
    sections = [s for s in doc.get("sections") or [] if isinstance(s, dict)]
    used = {w.get("id") for s in sections for w in s.get("widgets") or [] if isinstance(w, dict)}
    widgets: list[dict] = []
    section_top = 0
    for section in sections:
        items = []
        title = section.get("title")
        if isinstance(title, str) and title.strip():
            data = {}
            if "level" in section:
                data["level"] = section["level"]
            if section.get("description"):
                data["description"] = section["description"]
            heading = {"id": _unique_heading_id(section.get("id"), used), "type": "heading", "version": 1,
                       "title": title, "data": data}
            items.append((heading, (_GRID_COLS, 2 if section.get("description") else 1)))
        for w in section.get("widgets") or []:
            if isinstance(w, dict):
                items.append(({k: v for k, v in w.items() if k != "span"}, _v1_size(w)))
        x, y, shelf_h = 0, section_top, 0
        for widget, (w, h) in items:
            if x > 0 and x + w > _GRID_COLS:
                x, y, shelf_h = 0, y + shelf_h, 0
            widgets.append({**widget, "layout": {"x": x, "y": y, "w": w, "h": h}})
            x += w
            shelf_h = max(shelf_h, h)
        section_top = y + shelf_h
    return _compact(widgets)


def _doc_widgets(doc: Optional[dict]) -> list[dict]:
    """The doc's widgets in dashkit's summary order, (y, x, stored order); a v1 doc is flattened first."""
    doc = doc or {}
    if isinstance(doc.get("widgets"), list):
        widgets = [w for w in doc["widgets"] if isinstance(w, dict)]
    elif isinstance(doc.get("sections"), list):
        widgets = _flatten_v1(doc)
    else:
        widgets = []
    order = sorted(range(len(widgets)), key=lambda i: (_grid(widgets[i])["y"], _grid(widgets[i])["x"], i))
    return [widgets[i] for i in order]


def summarize_doc(doc: dict) -> str:
    """dashkit's `summarize(doc)`, line for line (src/core/summarize.ts). A v1 doc (sections with spans)
    is summarized as dashkit's `migrate()` would turn it into v2."""
    widgets = _doc_widgets(doc)
    return "\n".join([f'# {doc.get("title", "")} ({len(widgets)} widgets)', *map(_widget_line, widgets)])


async def _stored_doc(db, user_id: str, dashboard_id: Optional[str]) -> Optional[dict]:
    if not dashboard_id:
        return None
    row = await db["dashboards"].find_one({"id": dashboard_id, "user_id": user_id}, {"_id": 0, "doc": 1})
    return (row or {}).get("doc")


class _Layout:
    """Which widget ids exist, in summary order: what ops may refer to.

    Built from the editor's summary when one was sent (it is authoritative:
    it includes unsaved edits), else from the stored doc, then advanced by the
    ops already returned this turn and, within one call, by each accepted op.
    Mirrors only the id bookkeeping of dashkit's applyAll (positions are left
    to the editor, which places and compacts), plus the current dashboard and
    widget titles (so an op that keeps a title as it is is not rejected for
    markdown the user typed themselves).
    """

    def __init__(self, widgets: list[str], title: Optional[str] = None, widget_titles: Optional[dict] = None):
        self.widgets: list = list(widgets)
        self.title = title
        self.widget_titles: dict = dict(widget_titles or {})

    @classmethod
    def from_summary(cls, summary: str) -> "_Layout":
        widgets: list[str] = []
        title, widget_titles = None, {}
        for line in summary.splitlines():
            if title is None and not widgets and (m := _TITLE_LINE.match(line)):
                title = m.group(1)
            elif m := _WIDGET_DETAIL.match(line):
                widgets.append(m.group(1))
                widget_titles[m.group(1)] = m.group(3)
            elif m := _WIDGET_LINE.match(line):
                widgets.append(m.group(1))  # an id is usable even from a line in another format
        return cls(widgets, title, widget_titles)

    @classmethod
    def from_doc(cls, doc: Optional[dict]) -> "_Layout":
        widgets = _doc_widgets(doc)
        return cls([w.get("id") for w in widgets], (doc or {}).get("title"),
                   {w.get("id"): w.get("title") for w in widgets})

    def has_widget(self, widget_id) -> bool:
        return widget_id in self.widgets

    def _missing(self, widget_id, path: str) -> Optional[dict]:
        if self.has_widget(widget_id):
            return None
        return _fail("WIDGET_NOT_FOUND", path, f'No widget "{widget_id}"; use ids from dashboard_describe')

    def check(self, op: dict, at: str) -> Optional[dict]:
        """WIDGET_NOT_FOUND / DUPLICATE_ID for one op, against the current ids."""
        if "widgetId" in op and (found := self._missing(op["widgetId"], f"{at}/widgetId")):
            return found
        if op["op"] == "addWidget":
            if "after" in op and (found := self._missing(op["after"], f"{at}/after")):
                return found
            widget_id = op["widget"].get("id")
            if widget_id is not None and self.has_widget(widget_id):
                return _fail("DUPLICATE_ID", f"{at}/widget/id", f'Id "{widget_id}" is already used')
        if op["op"] == "setLayout":
            for j, item in enumerate(op["items"]):
                if found := self._missing(item["widgetId"], f"{at}/items/{j}/widgetId"):
                    return found
        return None

    def apply(self, op: dict) -> None:
        name = op.get("op")
        if name == "setTitle":
            self.title = op.get("title")
        elif name == "updateWidget" and "title" in (op.get("patch") or {}):
            self.widget_titles[op["widgetId"]] = op["patch"]["title"]
        elif name == "addWidget":
            widget = op.get("widget") or {}
            if widget.get("id") is None:
                return  # dashkit generates the id; no later op can name it
            after = op.get("after")
            index = self.widgets.index(after) + 1 if after in self.widgets else len(self.widgets)
            self.widgets.insert(index, widget["id"])
            if widget.get("title") is not None:
                self.widget_titles[widget["id"]] = widget["title"]
        elif name == "removeWidget" and op.get("widgetId") in self.widgets:
            self.widgets.remove(op["widgetId"])
            self.widget_titles.pop(op["widgetId"], None)


async def _layout(db, user_id, dashboard_id, summary, sink) -> _Layout:
    if isinstance(summary, str) and summary.strip():
        layout = _Layout.from_summary(summary)
    else:
        layout = _Layout.from_doc(await _stored_doc(db, user_id, dashboard_id))
    for op in sink or []:
        layout.apply(op)
    return layout


# ── executors ────────────────────────────────────────────────────────────────


async def dashboard_describe(db, user_id, dashboard_id=None, summary=None, dashboard_ops_sink=None, **_):
    if isinstance(summary, str) and summary.strip():
        text = summary
    else:
        doc = await _stored_doc(db, user_id, dashboard_id)
        if doc is None:
            return _fail("NOT_FOUND", "", "No dashboard is open in the editor.")
        text = summarize_doc(doc)
    result = {"summary": text}
    if dashboard_ops_sink:
        result["note"] = (f"This outline was taken before the {len(dashboard_ops_sink)} op(s) returned earlier "
                          "in this turn; those are applied on top of it.")
    return result


# Executors take the model's arguments as **args: everything else in the
# signature is injected by the registry or the orchestrator, so `args` is
# exactly what gets validated against the tool's parameter schema.


async def dashboard_apply(db, user_id, dashboard_id=None, summary=None, dashboard_ops_sink=None,
                          mongo_client=None, **args):
    error = _ops_error(args.get("ops")) or _schema_error(_VALIDATORS["dashboard_apply"], args)
    if error:
        return error
    ops = args["ops"]
    metrics, dimensions = _catalog_index()
    for i, op in enumerate(ops):
        at = f"/ops/{i}"
        if op["op"] == "setBinding":
            found = _binding_error(op["binding"], f"{at}/binding", metrics, dimensions)
        elif op["op"] == "addWidget":
            found = next((e for slot, b in (op["widget"].get("bindings") or {}).items()
                          if (e := _binding_error(b, f"{at}/widget/bindings/{slot}", metrics, dimensions))), None)
        else:
            found = None
        if found:
            return found
    layout = await _layout(db, user_id, dashboard_id, summary, dashboard_ops_sink)
    for i, op in enumerate(ops):
        found = layout.check(op, f"/ops/{i}") or _op_title_error(op, f"/ops/{i}", layout)
        if found:
            return found
        layout.apply(op)
    return _succeed(ops, dashboard_ops_sink)


async def dashboard_propose_widget(db, user_id, dashboard_id=None, summary=None, dashboard_ops_sink=None,
                                   mongo_client=None, **args):
    """dashkit's proposeTool: one `addWidget` (bindings inside the widget), placed `after` a widget
    when given, else at the bottom; the editor applies the type's default size when `size` is omitted."""
    error = _schema_error(_VALIDATORS["dashboard_propose_widget"], args) or _title_error(args.get("title"), "/title")
    if error:
        return error

    entry = _manifest_entry(args["type"]) or {}
    size = args.get("size")
    lo, hi = entry.get("minSize"), entry.get("maxSize")
    if size is not None and lo and hi:
        for axis in ("w", "h"):
            if not lo[axis] <= size[axis] <= hi[axis]:
                return _fail("SIZE_OUT_OF_RANGE", f"/size/{axis}",
                             f'Size {size["w"]}x{size["h"]} for "{args["type"]}" must be between '
                             f'{lo["w"]}x{lo["h"]} and {hi["w"]}x{hi["h"]}')

    bindings = args.get("bindings") or {}
    slots = {s["name"]: s for s in entry.get("slots", [])}
    for name, slot in slots.items():
        if slot.get("required") and name not in bindings:
            return _fail("SLOT_REQUIRED", f"/bindings/{name}", f'Slot "{name}" must be bound')
    metrics, dimensions = _catalog_index()
    for name, binding in bindings.items():
        if name not in slots:
            return _fail("SLOT_UNKNOWN", f"/bindings/{name}", f'"{args["type"]}" has no slot "{name}"')
        found = _binding_error(binding, f"/bindings/{name}", metrics, dimensions)
        if found:
            return found

    after = args.get("after")
    if after is not None:
        layout = await _layout(db, user_id, dashboard_id, summary, dashboard_ops_sink)
        if not layout.has_widget(after):
            return _fail("WIDGET_NOT_FOUND", "/after", f'No widget "{after}"; use ids from dashboard_describe')

    widget_id = uuid4().hex[:12]
    widget = {"id": widget_id, "type": args["type"]}
    for key in ("title", "size", "data"):
        if key in args:
            widget[key] = args[key]
    if bindings:
        widget["bindings"] = bindings
    op = {"op": "addWidget", "widget": widget}
    if after is not None:
        op["after"] = after
    return _succeed([op], dashboard_ops_sink, widgetId=widget_id)


def _rank(query: str, item: dict) -> int:
    key = item["key"].lower()
    if key == query:
        return 0
    if query in key:
        return 1
    if query in (item.get("label") or "").lower():
        return 2
    if query in (item.get("description") or "").lower():
        return 3
    return -1


def _search(items: list[dict], query: str) -> list[dict]:
    ranked = [(score, i, item) for i, item in enumerate(items) if (score := _rank(query, item)) >= 0]
    return [item for _, _, item in sorted(ranked, key=lambda r: (r[0], r[1]))[:_SEARCH_LIMIT]]


async def catalog_search(db, user_id, query=None, **_):
    error = _schema_error(_VALIDATORS["catalog_search"], {} if query is None else {"query": query})
    if error:
        return error
    catalog = build_catalog()
    q = query.strip().lower()
    metrics = []
    for m in _search(catalog["metrics"], q):
        row = {"key": m["key"], "label": m["label"]}
        if m.get("unit") is not None:
            row["unit"] = m["unit"]
        row.update({"format": m["format"], "dimensions": list(m.get("dimensions", []))})
        metrics.append(row)
    return {
        "metrics": metrics,
        "dimensions": [{"key": d["key"], "label": d["label"]} for d in _search(catalog["dimensions"], q)],
        "windows": [{"preset": w["preset"], "label": w["label"]} for w in catalog["windows"]],
    }


